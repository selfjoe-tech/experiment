-- Idempotent discovery notifications. Never expose this table to browsers.
-- Rollback: DROP TABLE IF EXISTS public.seo_discovery_events;
create table if not exists public.seo_discovery_events (
 id bigint generated by default as identity primary key,
 canonical_url text not null unique check (canonical_url ~ '^https://goongram[.]com/'),
 kind text not null check(kind in ('profile','video','image')),
 status text not null default 'queued' check(status in ('queued','sent','failed')),
 attempts integer not null default 0 check(attempts>=0),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 last_attempt_at timestamptz,
 last_error text
);
create index if not exists seo_discovery_status_idx
 on public.seo_discovery_events(status,created_at) where status <> 'sent';
alter table public.seo_discovery_events enable row level security;
revoke all on public.seo_discovery_events from public,anon,authenticated;
grant select,insert,update,delete on public.seo_discovery_events to service_role;
notify pgrst,'reload schema';
